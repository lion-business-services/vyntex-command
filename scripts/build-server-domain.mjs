// Bundles the pure TypeScript domain code the server needs into one plain JavaScript file the functions in api/ can
// import: api/_lib/domain.bundle.mjs. The rules about signing order, required boxes, expiry, reminders and the signed
// copy are written once, in src/domain/esign, and run in the browser (sample mode) and on the server (real requests).
//
//   node scripts/build-server-domain.mjs            writes api/_lib/domain.bundle.mjs
//   node scripts/build-server-domain.mjs --check    exits 1 when the file on disk is not what the sources produce
//
// pdf-lib stays outside the bundle: it is a dependency of the project, loaded only when a signed copy is made.
// The rule engine (src/domain/rules) is NOT in this bundle: it reaches the whole action layer and the browser session
// (src/platform/session), so it cannot run on the server as it is. docs/SERVER.md section 21 says what is missing.
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'api/_lib/domain.bundle.mjs');
const banner = '// GENERATED by scripts/build-server-domain.mjs from src/domain/esign. Do not edit: change the sources and build again.\n';

export async function bundleServerDomain() {
  const r = await build({
    stdin: { contents: "export * as esign from './src/domain/esign/index.ts';\n", resolveDir: root, loader: 'ts' },
    bundle: true, format: 'esm', platform: 'node', target: 'node20', write: false, legalComments: 'none',
    external: ['pdf-lib'], alias: { '@': path.join(root, 'src') }, banner: { js: banner.trimEnd() }, logLevel: 'silent',
  });
  return r.outputFiles[0].text;
}

/**
 * Writes the bundle when it differs from what is on disk. Called by scripts/build.mjs before every build, so a
 * deployment never ships rules older than its sources. The write goes through a temporary file and a rename: someone
 * importing the bundle at that moment reads the old file or the new one, never half of one.
 */
export async function writeServerDomain() {
  const text = await bundleServerDomain();
  if (fs.existsSync(out) && fs.readFileSync(out, 'utf8') === text) return false;
  const tmp = `${out}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, out);
  return true;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await bundleServerDomain();
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(out) && fs.readFileSync(out, 'utf8') === text;
    if (!same) { console.error('api/_lib/domain.bundle.mjs is out of date: run node scripts/build-server-domain.mjs'); process.exit(1); }
    console.log('api/_lib/domain.bundle.mjs is up to date');
  } else {
    const changed = await writeServerDomain();
    console.log(`${changed ? 'wrote' : 'unchanged:'} api/_lib/domain.bundle.mjs (${Math.round(text.length / 1024)} KB)`);
  }
}
